export function visiblePhotos(slug: string, hiddenPhotos: string[]): string[] {
  return (seriesPhotos[slug] ?? []).filter((url) => !hiddenPhotos.includes(url));
}

// A cover image falls back to the series' first visible photo when it's hidden.
export function coverPhoto(slug: string, cover: string, hiddenPhotos: string[]): string {
  if (!hiddenPhotos.includes(cover)) return cover;
  return visiblePhotos(slug, hiddenPhotos)[0] ?? cover;
}
